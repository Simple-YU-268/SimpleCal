/**
 * 前端树必须自包含。
 *
 * Docker 的前端阶段只 COPY code/web/，e2e 的「两次真实构建」夹具也只复制
 * code/web/{index.html,src,public}。前端源码里一旦出现跨出 code/web/src 的
 * 相对 import（早先的 '../../../app/vendor/ical/utc-recurrence.js' 就是这样），
 * 这两处构建都会当场失败——而且只有跑完整构建才看得出来。
 *
 * 这里做静态断言，把问题挡在单元测试这一层。
 */
import { describe, it, expect } from 'vitest';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, '..');
const srcRoot = path.join(webRoot, 'src');
const codeRoot = path.resolve(webRoot, '..');

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (full.endsWith('.js')) out.push(full);
  }
  return out;
}

// 只认真正的 import/export 语句：跳过注释与普通字符串里的 from '...'。
const SPECIFIER = /^\s*(?:import|export)\b[^;'"]*?from\s*['"]([^'"]+)['"]/gm;
const BARE_IMPORT = /^\s*import\s*['"]([^'"]+)['"]/gm;

function specifiersOf(file) {
  const text = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  const found = new Set();
  for (const re of [SPECIFIER, BARE_IMPORT]) {
    re.lastIndex = 0;
    let match;
    while ((match = re.exec(text)) !== null) found.add(match[1]);
  }
  return [...found];
}

describe('前端树自包含', () => {
  const files = walk(srcRoot);

  it('src 下有可扫描的模块', () => {
    expect(files.length).toBeGreaterThan(20);
  });

  it('相对 import 不得越出 code/web/src', () => {
    const escapes = [];
    for (const file of files) {
      for (const specifier of specifiersOf(file)) {
        if (!specifier.startsWith('.')) continue;
        const resolved = path.resolve(path.dirname(file), specifier);
        const rel = path.relative(srcRoot, resolved);
        if (rel.startsWith('..') || path.isAbsolute(rel)) {
          escapes.push(`${path.relative(webRoot, file)} → ${specifier}`);
        }
      }
    }
    expect(escapes, `前端不能依赖 code/web 之外的源码：\n${escapes.join('\n')}`).toEqual([]);
  });

  it('相对 import 指向的文件都存在', () => {
    const missing = [];
    for (const file of files) {
      for (const specifier of specifiersOf(file)) {
        if (!specifier.startsWith('.')) continue;
        const resolved = path.resolve(path.dirname(file), specifier);
        if (!existsSync(resolved)) {
          missing.push(`${path.relative(webRoot, file)} → ${specifier}`);
        }
      }
    }
    expect(missing, `相对 import 指向不存在的文件：\n${missing.join('\n')}`).toEqual([]);
  });

  it('重复规则的日期算术与共享源一致（生成物没漂移）', () => {
    const shared = readFileSync(path.join(codeRoot, 'shared', 'utc-recurrence.mjs'), 'utf8').replace(/\r\n/g, '\n');
    const generated = readFileSync(path.join(srcRoot, 'js', 'utc-recurrence.js'), 'utf8').replace(/\r\n/g, '\n');
    expect(generated).toContain('AUTO-GENERATED by code/scripts/sync-utc-recurrence.mjs');
    expect(generated.slice(generated.indexOf('*/\n') + 3)).toBe(shared);
  });
});
