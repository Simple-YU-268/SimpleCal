import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { recurrenceZone, wallDate, utcPeriodStarts, utcPeriodIndex } from '../vendor/ical/utc-recurrence.js';

/**
 * 重复规则的日期算术是前后端共用的一份源：code/shared/utc-recurrence.mjs。
 *
 * 前端不能直接 import 后端那份（Docker 前端阶段只 COPY code/web/，e2e 夹具也
 * 只复制前端树），所以两边各留一份生成物。生成物一旦手改，前后端就会在日期
 * 算术上悄悄分叉——这正是日期语料要防的问题，所以这里把「生成物 == 源」钉死。
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const codeRoot = path.resolve(here, '..', '..');
const toLf = (text) => text.replace(/\r\n/g, '\n');

test('后端生成物与共享源逐字一致', () => {
  const shared = toLf(readFileSync(path.join(codeRoot, 'shared', 'utc-recurrence.mjs'), 'utf8'));
  const generated = toLf(readFileSync(path.join(codeRoot, 'app', 'vendor', 'ical', 'utc-recurrence.js'), 'utf8'));
  assert.match(generated, /AUTO-GENERATED by code\/scripts\/sync-utc-recurrence\.mjs/);
  const marker = generated.indexOf('*/\n');
  assert.notEqual(marker, -1, '生成物缺少 AUTO-GENERATED 头');
  assert.equal(generated.slice(marker + 3), shared, '生成物已漂移：请运行 node scripts/sync-utc-recurrence.mjs');
});

test('共享源的日期算术仍然可用', () => {
  assert.equal(recurrenceZone('America/New_York'), 'America/New_York');
  assert.equal(recurrenceZone('Not/AZone'), null);
  assert.equal(recurrenceZone(null), null);

  // 2026-03-01T14:00:00Z 是纽约 09:00（EST）；同一墙钟在夏令时后是 13:00Z。
  const start = new Date('2026-03-01T14:00:00.000Z');
  const wall = wallDate(start.getTime(), 'America/New_York');
  assert.equal(wall.toISOString(), '2026-03-01T09:00:00.000Z');

  const rule = {
    freq: 'weekly', interval: 1, wkst: 0, byWeekday: [0],
    timezone: 'America/New_York',
  };
  const starts = utcPeriodStarts(rule, new Date(Date.UTC(2026, 2, 1, 9)), 0);
  assert.deepEqual(starts.map((d) => d.toISOString()), ['2026-03-01T09:00:00.000Z']);
  assert.equal(utcPeriodIndex(rule, new Date(Date.UTC(2026, 2, 1, 9)), new Date(Date.UTC(2026, 2, 8, 9))), 1);
});
